    public static boolean has(String name) {
        return name != null && GLYPHS.containsKey(name.toLowerCase(Locale.ROOT));
    }

    /** Draws the glyph at 1 GUI pixel per cell inside a 16x16 box at (x, y). */
    public static void draw(GuiGraphics g, String name, int x, int y, int color) {
        String[] rows = GLYPHS.get(name == null ? "generic" : name.toLowerCase(Locale.ROOT));
        if (rows == null) rows = GLYPHS.get("generic");
        for (int r = 0; r < rows.length; r++) {
            String row = rows[r];
            int start = -1;
            for (int c = 0; c <= row.length(); c++) {
                boolean lit = c < row.length() && row.charAt(c) == '#';
                if (lit && start < 0) start = c;
                if (!lit && start >= 0) {
                    g.fill(x + start, y + r, x + c, y + r + 1, color);
                    start = -1;
                }
            }
        }
    }

    /** Draws the glyph scaled by an integer factor (sidebar logo, empty states). */
    public static void draw(GuiGraphics g, String name, int x, int y, int color, int scale) {
        if (scale <= 1) {
            draw(g, name, x, y, color);
            return;
        }
        String[] rows = GLYPHS.get(name == null ? "generic" : name.toLowerCase(Locale.ROOT));
        if (rows == null) rows = GLYPHS.get("generic");
        for (int r = 0; r < rows.length; r++) {
            String row = rows[r];
            int start = -1;
            for (int c = 0; c <= row.length(); c++) {
                boolean lit = c < row.length() && row.charAt(c) == '#';
                if (lit && start < 0) start = c;
                if (!lit && start >= 0) {
                    g.fill(x + start * scale, y + r * scale, x + c * scale, y + (r + 1) * scale, color);
                    start = -1;
                }
            }
        }
    }
